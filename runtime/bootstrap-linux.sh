#!/usr/bin/env bash
# OpenMaxFX — bootstrap Max Payne 1 for modern Linux (Wine / Proton)
# Usage: ./bootstrap-linux.sh /path/to/MaxPayneInstallDir
set -euo pipefail

ROOT="$(cd "$(dirname "$0")" && pwd)"
# shellcheck disable=SC1091
source "$ROOT/env.sh" 2>/dev/null || true

GAME_DIR="${1:-}"
if [[ -z "$GAME_DIR" || ! -d "$GAME_DIR" ]]; then
  echo "Usage: $0 /path/to/MaxPayne" >&2
  echo "Expect MaxPayne.exe (or similar) in that directory." >&2
  exit 1
fi
GAME_DIR="$(cd "$GAME_DIR" && pwd)"
OVERLAY="$ROOT/overlays"
mkdir -p "$OVERLAY"/{dxvk,d3d8to9,dsoal}

echo "==> Game: $GAME_DIR"

have() { command -v "$1" >/dev/null 2>&1; }

download() {
  local url="$1" out="$2"
  if [[ -f "$out" ]]; then
    echo "    exists: $out"
    return 0
  fi
  echo "    fetch $url"
  curl -fsSL -L --retry 3 -o "$out" "$url"
}

# --- d3d8to9 (asset is d3d8.dll; version bumps — pin known-good) ---
D3D8_VER="1.16.0"
if [[ ! -f "$OVERLAY/d3d8to9/d3d8.dll" ]]; then
  download \
    "https://github.com/crosire/d3d8to9/releases/download/v${D3D8_VER}/d3d8.dll" \
    "$OVERLAY/d3d8to9/d3d8.dll" || true
fi

# --- DXVK (d3d9) ---
DXVK_VER="2.6.1"
DXVK_TGZ="$OVERLAY/dxvk/dxvk-${DXVK_VER}.tar.gz"
if [[ ! -d "$OVERLAY/dxvk/x32" ]]; then
  download \
    "https://github.com/doitsujin/dxvk/releases/download/v${DXVK_VER}/dxvk-${DXVK_VER}.tar.gz" \
    "$DXVK_TGZ"
  tar -xzf "$DXVK_TGZ" -C "$OVERLAY/dxvk" --strip-components=1
fi

# --- DSOAL (optional; may 404 on tag changes — non-fatal) ---
if [[ ! -f "$OVERLAY/dsoal/dsound.dll" ]]; then
  download \
    "https://github.com/kcat/dsoal/releases/download/v1.3/dsoal-v1.3.zip" \
    "$OVERLAY/dsoal/dsoal.zip" 2>/dev/null || echo "    (dsoal download skipped — install manually if needed)"
  if [[ -f "$OVERLAY/dsoal/dsoal.zip" ]]; then
    unzip -qo "$OVERLAY/dsoal/dsoal.zip" -d "$OVERLAY/dsoal" || true
  fi
fi

# --- Install overlays into game dir ---
install_dll() {
  local src="$1" name="$2"
  if [[ -f "$src" ]]; then
    cp -f "$src" "$GAME_DIR/$name"
    echo "    installed $name"
  else
    echo "    MISSING $src — skip $name"
  fi
}

echo "==> Installing wrappers into game dir"
install_dll "$OVERLAY/d3d8to9/d3d8.dll" "d3d8.dll"
# DXVK d3d9 for 32-bit Max Payne
if [[ -f "$OVERLAY/dxvk/x32/d3d9.dll" ]]; then
  cp -f "$OVERLAY/dxvk/x32/d3d9.dll" "$GAME_DIR/d3d9.dll"
  echo "    installed d3d9.dll (DXVK x32)"
fi
# DSOAL
find "$OVERLAY/dsoal" -iname 'dsound.dll' | head -1 | while read -r f; do
  cp -f "$f" "$GAME_DIR/dsound.dll"
  echo "    installed dsound.dll (DSOAL)"
done

# --- Launch helper ---
LAUNCH="$GAME_DIR/launch-openmaxfx.sh"
EXE=""
for c in MaxPayne.exe maxpayne.exe MaxPayne.EXE; do
  [[ -f "$GAME_DIR/$c" ]] && EXE="$c" && break
done
if [[ -z "$EXE" ]]; then
  EXE="$(find "$GAME_DIR" -maxdepth 1 -iname 'maxpayne*.exe' | head -1 | xargs -r basename)"
fi

# Prefer system Wine for non-Steam installs (Proton often exits silently outside Steam).
# Set OPENMAXFX_USE_PROTON=1 to force Proton. OPENMAXFX_PROTON_DIR overrides path.
USE_PROTON="${OPENMAXFX_USE_PROTON:-0}"
PROTON_DIR="${OPENMAXFX_PROTON_DIR:-${PROTON_DIR:-$HOME/.steam/steam/steamapps/common/Proton 9.0 (Beta)}}"

# Quoted heredoc so $(dirname "$0") is NOT expanded at generate-time (bug → cd ".")
cat >"$LAUNCH" <<'EOF'
#!/usr/bin/env bash
# Generated by OpenMaxFX runtime/bootstrap-linux.sh
set -euo pipefail
cd "$(dirname "$0")"
GAME_DIR="$(pwd)"
LOG="$GAME_DIR/openmaxfx-launch.log"
exec >>"$LOG" 2>&1

echo
echo "======== $(date -Iseconds) launch ========"

export WINEPREFIX="${WINEPREFIX:-$GAME_DIR/.wine}"
mkdir -p "$WINEPREFIX"
# d3d8→d3d9→DXVK; prefer builtin dinput when ASI loader is parked
export WINEDLLOVERRIDES="${WINEDLLOVERRIDES:-d3d8=n,b;d3d9=n,b;dsound=n,b}"
export DXVK_FRAME_RATE="${DXVK_FRAME_RATE:-60}"
export DXVK_HUD="${DXVK_HUD:-}"
# Hybrid NVIDIA: only when asked (auto-offload often breaks EGL → invisible window)
if [[ "${OPENMAXFX_USE_NVIDIA:-0}" == "1" ]]; then
  export DXVK_FILTER_DEVICE_NAME="${DXVK_FILTER_DEVICE_NAME:-NVIDIA}"
  export __NV_PRIME_RENDER_OFFLOAD=1
  export __VK_LAYER_NV_optimus=NVIDIA_only
  export __GLX_VENDOR_LIBRARY_NAME=nvidia
elif [[ -f /usr/share/vulkan/icd.d/nvidia_icd.json ]]; then
  # DXVK on NVIDIA ICD without GLX offload (EGL is broken on some hybrids)
  export VK_ICD_FILENAMES="${VK_ICD_FILENAMES:-/usr/share/vulkan/icd.d/nvidia_icd.json}"
fi

EXE="MaxPayne.exe"
for c in MaxPayne.exe maxpayne.exe MaxPayne.EXE; do
  [[ -f "./$c" ]] && EXE="$c" && break
done

log() { echo "==> $*"; }

# Localized pack: x_<lang>.ras (not english/data/music/level*) — park hi-res + ASI
_loc=""
for _f in "$GAME_DIR"/x_*.ras; do
  [[ -f "$_f" ]] || continue
  _b="$(basename "$_f")"; _b="${_b#x_}"; _b="${_b%.ras}"
  _b="$(printf '%s' "$_b" | tr '[:upper:]' '[:lower:]')"
  case "$_b" in english|data|music|level|level[0-9]*) ;; *) _loc="$_b"; break ;; esac
done
if [[ -n "${_loc}" ]]; then
  if [[ -d "$GAME_DIR/data.disabled-italian" && ! -e "$GAME_DIR/data.disabled-hires" ]]; then
    mv "$GAME_DIR/data.disabled-italian" "$GAME_DIR/data.disabled-hires"
  fi
  if [[ -d "$GAME_DIR/data" && ! -f "$GAME_DIR/data/globalconfig.txt" && ! -L "$GAME_DIR/data" ]]; then
    log "Localized (${_loc}): parking FixPack data/ → data.disabled-hires"
    rm -rf "$GAME_DIR/data.disabled-hires"
    mv "$GAME_DIR/data" "$GAME_DIR/data.disabled-hires"
  fi
  if [[ -f "$GAME_DIR/dinput.dll" ]]; then
    sz=$(stat -c%s "$GAME_DIR/dinput.dll" 2>/dev/null || echo 0)
    if [[ "$sz" -gt 500000 ]]; then
      log "Localized (${_loc}): parking ASI dinput.dll"
      mv -f "$GAME_DIR/dinput.dll" "$GAME_DIR/dinput.dll.asi-loader.bak"
    fi
  fi
fi
if [[ "${OPENMAXFX_USE_PROTON:-0}" == "1" ]]; then
  PROTON_DIR="${OPENMAXFX_PROTON_DIR:-$HOME/.steam/steam/steamapps/common/Proton 9.0 (Beta)}"
  if [[ -x "$PROTON_DIR/proton" ]]; then
    export STEAM_COMPAT_DATA_PATH="${STEAM_COMPAT_DATA_PATH:-$GAME_DIR/.proton_prefix}"
    export STEAM_COMPAT_CLIENT_INSTALL_PATH="${STEAM_COMPAT_CLIENT_INSTALL_PATH:-$HOME/.steam/steam}"
    mkdir -p "$STEAM_COMPAT_DATA_PATH"
    log "Proton: $PROTON_DIR"
    exec "$PROTON_DIR/proton" run "./$EXE" "$@"
  fi
  log "Proton requested but not found at $PROTON_DIR — falling back to wine"
fi

if ! command -v wine >/dev/null 2>&1; then
  echo "ERROR: wine not found. Install wine-staging (or wine)."
  exit 1
fi

# Wayland / multi-monitor: virtual desktop so the config dialog actually appears.
# Disable: OPENMAXFX_VIRTUAL_DESKTOP=0
VD="${OPENMAXFX_VIRTUAL_DESKTOP:-1280x720}"
log "Wineprefix: $WINEPREFIX"
log "Wine: $(command -v wine) → ./$EXE"
log "Log: $LOG"
if [[ "$VD" != "0" && "$VD" != "off" ]]; then
  log "Virtual desktop: ${VD} (set OPENMAXFX_VIRTUAL_DESKTOP=0 to disable)"
  exec wine explorer "/desktop=OpenMaxPayne,${VD}" "./$EXE" "$@"
fi
exec wine "./$EXE" "$@"
EOF
# Patch EXE name if non-default (keep script simple: rewrite line)
if [[ -n "$EXE" && "$EXE" != "MaxPayne.exe" ]]; then
  sed -i "s/^EXE=\"MaxPayne.exe\"/EXE=\"$EXE\"/" "$LAUNCH"
fi
chmod +x "$LAUNCH"

echo
echo "Done."
echo "  Launch: $LAUNCH"
echo "  Tip: Widescreen Fix (ThirteenAG) — drop manually into game dir if desired:"
echo "       https://github.com/ThirteenAG/WidescreenFixesPack/releases"
echo "  Tip: insert Max Payne CD and extract Disk1 CABs with unshield for a full install tree."
